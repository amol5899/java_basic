package solid_priciples;

public class DependencyInversion {
	/*
	 * The Dependency Inversion Principle (DIP) is a principle in object-oriented
	 * design that states that High-level modules should not depend on low-level
	 * modules. Both should depend on abstractions . Additionally, abstractions
	 * should not depend on details. Details should depend on abstractions.
	 * 
	 * In simpler terms, the DIP suggests that classes should rely on abstractions
	 * (e.g., interfaces or abstract classes) rather than concrete implementations.
	 * This allows for more flexible and decoupled code, making it easier to change
	 * implementations without affecting other parts of the codebase.
	 * 
	 * Example : In a software development team, developers depend on an abstract
	 * version control system (e.g., Git) to manage and track changes to the
	 * codebase. They don't depend on specific details of how Git works internally.
	 */
}
